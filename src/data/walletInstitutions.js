// Dynamic text badge generator for custom unnamed wallets
export const createTextBadge = (bgColor, textColor, text, subtext = '', rx = 24) => {
  const cleanBg = String(bgColor || '').replace(/#/g, '%23')
  const cleanText = String(textColor || '').replace(/#/g, '%23')
  const fontSize = text.length > 6 ? '12' : text.length > 4 ? '14' : '17'
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 80 80"><rect width="80" height="80" rx="${rx}" fill="${cleanBg}"/><text x="40" y="${subtext ? '37' : '46'}" text-anchor="middle" font-size="${fontSize}" font-weight="900" fill="${cleanText}" font-family="-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,sans-serif">${text}</text>${subtext ? `<text x="40" y="54" text-anchor="middle" font-size="8.5" font-weight="800" fill="${cleanText}" opacity="0.85" font-family="-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,sans-serif">${subtext}</text>` : ''}</svg>`
  return `data:image/svg+xml;utf8,${svg}`
}

export const createSvgBadge = (bgColor, contentSvg, rx = 24) => {
  const cleanBg = String(bgColor || '').replace(/#/g, '%23')
  const cleanContent = String(contentSvg || '').replace(/#/g, '%23')
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 80 80"><rect width="80" height="80" rx="${rx}" fill="${cleanBg}"/>${cleanContent}</svg>`
  return `data:image/svg+xml;utf8,${svg}`
}

const DYNAMIC_BADGE_PALETTES = [
  { bg: '#0284C7', fg: '#FFFFFF' },
  { bg: '#0D9488', fg: '#FFFFFF' },
  { bg: '#10B981', fg: '#FFFFFF' },
  { bg: '#8B5CF6', fg: '#FFFFFF' },
  { bg: '#D946EF', fg: '#FFFFFF' },
  { bg: '#F59E0B', fg: '#18181B' },
  { bg: '#F97316', fg: '#FFFFFF' },
  { bg: '#EC4899', fg: '#FFFFFF' },
  { bg: '#6366F1', fg: '#FFFFFF' },
]

function getDynamicInitialsBadge(name) {
  const clean = String(name || 'Akun').trim()
  let hash = 0
  for (let i = 0; i < clean.length; i++) {
    hash = clean.charCodeAt(i) + ((hash << 5) - hash)
  }
  const palette = DYNAMIC_BADGE_PALETTES[Math.abs(hash) % DYNAMIC_BADGE_PALETTES.length]
  const words = clean.split(/\s+/).filter(Boolean)
  const initials =
    words.length >= 2
      ? (words[0][0] + words[1][0]).toUpperCase()
      : clean.substring(0, 2).toUpperCase()
  return createTextBadge(palette.bg, palette.fg, initials)
}

